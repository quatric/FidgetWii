#!/usr/bin/env python3
"""Pre-render the HUD fonts into GX I8 glyph atlases.

Usage: make_font.py <regular.otf> <bold.otf>

Writes data/font_regular.bin, data/font_bold.bin and source/font_data.h.
Only printable ASCII is rendered. Requires Pillow.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
ATLAS_W = 512
CHARS = [chr(c) for c in range(32, 127)]

# (name, font argument index, pixel size)
FONTS = [("regular", 1, 22), ("bold", 2, 56)]


def build(name, path, size):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()

    glyphs = []
    x = y = row_h = 0
    pad = 2
    placed = []
    for ch in CHARS:
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(r - l, 0), max(b - t, 0)
        if x + w + pad > ATLAS_W:
            x = 0
            y += row_h + pad
            row_h = 0
        placed.append((ch, x, y, w, h, l, t))
        x += w + pad
        row_h = max(row_h, h)
    height = y + row_h
    height = (height + 3) // 4 * 4

    atlas = Image.new("L", (ATLAS_W, height), 0)
    draw = ImageDraw.Draw(atlas)
    for ch, gx, gy, w, h, l, t in placed:
        if w and h:
            draw.text((gx - l, gy - t), ch, font=font, fill=255, anchor="ls")
        glyphs.append((gx, gy, w, h, l, t, round(font.getlength(ch) * 4)))

    # GX I8 layout: 8x4 texel blocks
    px = atlas.load()
    data = bytearray()
    for ty in range(0, height, 4):
        for tx in range(0, ATLAS_W, 8):
            for yy in range(4):
                for xx in range(8):
                    data.append(px[tx + xx, ty + yy])
    (ROOT / "data" / f"font_{name}.bin").write_bytes(data)

    lines = [f"static const FontGlyph font_{name}_glyphs[{len(glyphs)}] = {{"]
    for g in glyphs:
        lines.append("    {%d, %d, %d, %d, %d, %d, %d}," % g)
    lines.append("};")
    lines.append(
        f"static const FontInfo font_{name}_info = {{{size}, {ascent}, {descent}, "
        f"{ATLAS_W}, {height}, font_{name}_glyphs}};"
    )
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)

    out = [
        "// Generated by scripts/make_font.py - do not edit",
        "#ifndef FONT_DATA_H",
        "#define FONT_DATA_H",
        "",
        "typedef struct",
        "{",
        "    short x, y, w, h;     // position in the atlas",
        "    short left, top;      // offset from the pen position on the baseline",
        "    short advance;        // in quarter pixels",
        "} FontGlyph;",
        "",
        "typedef struct",
        "{",
        "    int size, ascent, descent;",
        "    int atlas_w, atlas_h;",
        "    const FontGlyph *glyphs; // printable ASCII, starting at ' '",
        "} FontInfo;",
        "",
    ]
    for name, arg, size in FONTS:
        out.append(build(name, sys.argv[arg], size))
        out.append("")
    out.append("#endif")
    (ROOT / "source" / "font_data.h").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
